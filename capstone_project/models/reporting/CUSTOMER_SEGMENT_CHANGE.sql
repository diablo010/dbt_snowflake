SELECT 
    EXTRACT(WEEK FROM S.SALE_DATE) AS WEEK,
    C.CUSTOMER_SEGMENT,
    COUNT(DISTINCT S.CUSTOMER_ID) AS NO_OF_CUSTOMERS
FROM FCT_SALES S
LEFT JOIN DIM_CUSTOMER C
ON S.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY 1, 2
ORDER BY 1, 2